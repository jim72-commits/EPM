-- ---------------------------------------------------------------------------
-- Helper: does the authed user hold a candidate profile?
-- ---------------------------------------------------------------------------

create or replace function public.has_candidate_profile()
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (
    select 1 from public.candidate_profiles cp where cp.user_id = auth.uid()
  );
$$;

revoke all on function public.has_candidate_profile() from public;
grant execute on function public.has_candidate_profile() to authenticated;

-- ---------------------------------------------------------------------------
-- Storage: private resume bucket + policies
--
-- Files are keyed by {user_id}/{uuid}.{ext}. Candidates own their own prefix.
-- Employer/admin reads are intentionally NOT granted here — employers will
-- receive time-limited signed URLs generated by the server after verifying
-- the request against job_applications (Phase B). This keeps storage RLS
-- simple and auditable while employer access is mediated at the app layer.
-- ---------------------------------------------------------------------------

insert into storage.buckets (id, name, public)
values ('candidate-resumes', 'candidate-resumes', false)
on conflict (id) do nothing;

create policy "resumes_candidate_select_own"
  on storage.objects for select
  to authenticated
  using (
    bucket_id = 'candidate-resumes'
    and (auth.uid())::text = (storage.foldername(name))[1]
  );

create policy "resumes_candidate_insert_own"
  on storage.objects for insert
  to authenticated
  with check (
    bucket_id = 'candidate-resumes'
    and (auth.uid())::text = (storage.foldername(name))[1]
  );

create policy "resumes_candidate_update_own"
  on storage.objects for update
  to authenticated
  using (
    bucket_id = 'candidate-resumes'
    and (auth.uid())::text = (storage.foldername(name))[1]
  )
  with check (
    bucket_id = 'candidate-resumes'
    and (auth.uid())::text = (storage.foldername(name))[1]
  );

create policy "resumes_candidate_delete_own"
  on storage.objects for delete
  to authenticated
  using (
    bucket_id = 'candidate-resumes'
    and (auth.uid())::text = (storage.foldername(name))[1]
  );
